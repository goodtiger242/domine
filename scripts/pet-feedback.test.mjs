import assert from "node:assert/strict";
import { loadTS } from "./pet-test-loader.mjs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
const { rewardText, noticePages, nextGoal, MAX_XP } = loadTS("lib/domine/pet-progress.ts");
const { SHOP } = loadTS("lib/domine/pet-catalog.ts");
const { queueSpeech } = loadTS("lib/domine/pet-bubble.ts");
const reward = { coins: 4, xp: 8, levelCoins: 0, newEntries: [], newBadges: [] };
assert.equal(rewardText(reward), "+4 코인 · +8 XP");
assert.equal(rewardText(), "");
assert.equal(rewardText({ ...reward, coins: 0, xp: 0 }), "");
assert.match(rewardText({ ...reward, coins: 0, xp: 0, skipped: "TOO_FAST" }), /천천히/);
assert.equal(rewardText({ ...reward, levelCoins: 10 }), "+14 코인 · +8 XP");
const cheapest = [...SHOP].sort((a, b) => a.price - b.price)[0];
assert.equal(nextGoal(39, 0, []), `${cheapest.name}까지 ${cheapest.price}코인`);
assert.equal(nextGoal(0, 999, []), `${cheapest.name}을(를) 살 수 있어요`);
assert.equal(nextGoal(39, 999, SHOP.map(item => item.id)), "다음 레벨까지 1 XP");
assert.equal(nextGoal(MAX_XP, 999, SHOP.map(item => item.id)), "");
assert.ok(!nextGoal(0, 999, [cheapest.id]).includes(cheapest.name));
const parts = [rewardText(reward), `다음 목표 · ${nextGoal(0, 40, [])}`];
assert.deepEqual(noticePages(parts, () => true), [parts.join(" · ")]);
assert.deepEqual(noticePages(parts, text => text.length <= 30), parts);
const pages = noticePages(parts, text => text.length <= 6);
assert.ok(pages.every(text => text.length <= 6)); assert.equal(pages.join(""), parts.join(""));
const normal = {text:"밥 맛있!", speaker:"dog"}, arrival = {text:"들판에 왔어요", speaker:"dog", arrival:true};
let queue = queueSpeech([normal], arrival);
assert.equal(queue[0], arrival); assert.equal(queue[1], normal);
const next = {...normal, text:"반가워요"}; queue = queueSpeech(queue, next);
assert.deepEqual(queue, [arrival, next]); assert.equal(queue.slice(1)[0], next);
const Feedback = loadTS("app/games/PetFeedback.tsx").default;
const html = renderToStaticMarkup(createElement(Feedback, {result:{reward, player:{level:2}}, previousLevel:1}));
assert.doesNotMatch(html, /코인|XP|다음 목표|자랐어요|pet-reward/);
assert.match(html, /pet-level-particle/);
console.log("Pet feedback: reward/goal strings, measured single-line pages, arrival priority and nonverbal scene passed.");
