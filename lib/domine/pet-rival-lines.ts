function seedRoll(seed: number): number {
  let value = seed >>> 0;
  value = Math.imul(value ^ (value >>> 16), 0x21f0aaad);
  value = Math.imul(value ^ (value >>> 15), 0x735a2d97);
  return (value ^ (value >>> 15)) >>> 0;
}

/** variant는 small 또는 dog:small 형식. 길고양이는 owner 대사를 하지 않는다. */
export function rivalLine(
  species: RivalSpecies,
  moment: RivalMoment,
  opts: { variant?: string; seed: number; last?: string; name?: string; owner?: string },
): string {
  const variant = opts.variant?.startsWith(`${species}:`) ? opts.variant : `${species}:${opts.variant}`;
  if (moment === "owner" && (variant === "cat:stray" || (species !== "dog" && species !== "cat"))) return "";
  const name = opts.name?.trim();
  const owner = opts.owner?.trim();
  const pool = [...RIVAL_LINES[species][moment], ...(RIVAL_VARIANT_LINES[variant]?.[moment] ?? [])]
    .filter(line => (!line.includes("{name}") || name) && (!line.includes("{owner}") || owner))
    .map(line => line.replaceAll("{name}", name ?? "").replaceAll("{owner}", owner ?? ""))
    .filter(line => Array.from(line).length <= 28 && !/[\r\n]/.test(line));
  const fresh = pool.filter(line => line !== opts.last);
  const choices = fresh.length ? fresh : pool;
  return choices[seedRoll(opts.seed) % choices.length] ?? "";
}

export function shouldSpeak(moment: RivalMoment, seed: number): boolean {
  if (moment === "enter" || moment === "win" || moment === "lose") return true;
  const chance = moment === "crit_deal" || moment === "crit_take" || moment === "low" ? 70 : 25;
  return seedRoll(seed) % 100 < chance;
}
