/** 같은 키에서 매번 무작위로 하나 (이전과 같은 말이 연달아 나오지 않게 한다) */
const last: Record<string, string> = {};
export function line(key: string): string {
  const list = LINES[key];
  if (!list || list.length === 0) return "";
  let s = list[Math.floor(Math.random() * list.length)];
  if (list.length > 1 && s === last[key]) {
    s = list[(list.indexOf(s) + 1) % list.length];
  }
  last[key] = s;
  return s;
}

/** 서버가 돌려준 거절 안내를 도미의 말투로 바꾼다 */
export function rejectLine(msg: string): string {
  if (msg.includes("배가 불러")) return line("reject_full");
  if (msg.includes("기분이 최고")) return line("reject_mood");
  if (msg.includes("반짝반짝")) return line("reject_brush");
  if (msg.includes("깨끗")) return line("reject_clean");
  if (msg.includes("쉬는 중")) return line("reject_wait");
  if (msg.includes("사람이 많")) return line("reject_crowd");
  return msg;
}
